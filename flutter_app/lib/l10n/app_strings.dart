  /// Vidjet konteksti yo'q joylar (repozitoriylar, kontrollerlar, background
  /// isolate) uchun joriy til. SettingsController uni yangilab turadi —
  /// shunda hech bir qatlamda matn qotib qolmaydi.
  static String currentLocale = 'uz';

  /// Joriy tildagi matn.
  static String t(String key) => text(currentLocale, key);

  static String text(String locale, String key) {
    final lang = supportedLocales.contains(locale) ? locale : 'uz';
    // Tarjima topilmasa avval inglizchaga tushamiz: ruscha/arabcha/koreyscha
    // interfeysda kutilmaganda o'zbekcha matn chiqib qolmasin.
    return _values[lang]?[key] ??
        _values['en']?[key] ??
        _values['uz']?[key] ??
        key;
  }
